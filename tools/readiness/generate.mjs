// Generates the feature readiness registry from FEATURE_MATRIX.md, so the app never hand-writes a status.
// Usage: node tools/readiness/generate.mjs            (writes apps/mobile/src/readiness/registry.ts)
//        node tools/readiness/generate.mjs --check    (exits 1 if the committed registry is stale)
/* global console, process */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { parseMatrix } from "./parse.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const matrixPath = join(root, "FEATURE_MATRIX.md");
const outPath = join(root, "apps", "mobile", "src", "readiness", "registry.ts");

const { date, entries } = parseMatrix(readFileSync(matrixPath, "utf8"));

// The commit that last changed the matrix. Stable until the matrix changes, so --check does not go stale on every commit.
function matrixCommit() {
  try {
    return (
      execSync("git log -1 --format=%h -- FEATURE_MATRIX.md", { cwd: root }).toString().trim() ||
      "unknown"
    );
  } catch {
    return "unknown";
  }
}

const raw = `// GENERATED by tools/readiness/generate.mjs from FEATURE_MATRIX.md. Do not edit by hand.
// Matrix date: ${date}. Entries: ${entries.length}.

import type { ReadinessEntry } from "./model";

export const REGISTRY_VERSION = 1;
export const MATRIX_DATE = ${JSON.stringify(date)};
export const MATRIX_COMMIT = ${JSON.stringify(matrixCommit())};

export const REGISTRY: readonly ReadinessEntry[] = ${JSON.stringify(entries, null, 2)};
`;

// Formatted with the repository's Prettier settings, so the committed file is stable under format:check.
const config = (await resolveConfig(outPath)) ?? {};
const body = await format(raw, { ...config, filepath: outPath });

function currentFile() {
  try {
    return readFileSync(outPath, "utf8");
  } catch {
    return "";
  }
}

if (process.argv.includes("--check")) {
  if (currentFile() !== body) {
    console.error("registry.ts is stale: run node tools/readiness/generate.mjs");
    process.exit(1);
  }
  console.log(`registry.ts is up to date (${entries.length} entries)`);
} else {
  writeFileSync(outPath, body);
  console.log(`wrote ${outPath} (${entries.length} entries)`);
}
